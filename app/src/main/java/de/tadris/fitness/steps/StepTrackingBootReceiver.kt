package de.tadris.fitness.steps

import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import androidx.core.content.ContextCompat
import de.tadris.fitness.Instance

class StepTrackingBootReceiver : BroadcastReceiver() {

    override fun onReceive(context: Context, intent: Intent) {
        val action = intent.action ?: return
        if (action != Intent.ACTION_BOOT_COMPLETED && action != Intent.ACTION_MY_PACKAGE_REPLACED) return

        val prefs = Instance.getInstance(context).userPreferences
        if (!prefs.stepTrackingEnabled) return

        ContextCompat.startForegroundService(
            context,
            Intent(context, StepTrackingService::class.java)
        )
    }
}
